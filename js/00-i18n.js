  const STORAGE_KEY = "appLang";
  let currentLang = localStorage.getItem(STORAGE_KEY) || "pt";

  /**
   * Traduz uma chave. Faz fallback para PT e depois para a própria chave
   * (ou para um texto de fallback explícito), para nunca mostrar undefined.
   */
  function t(key, fallback) {
    const dict = DICTS[currentLang] || DICTS.pt;
    if (dict && Object.prototype.hasOwnProperty.call(dict, key)) return dict[key];
    if (DICTS.pt && Object.prototype.hasOwnProperty.call(DICTS.pt, key)) return DICTS.pt[key];
    return fallback !== undefined ? fallback : key;
  }

  /** Aplica as traduções a todo o DOM (texto, title, placeholder, alt). */
  function applyTranslations(root) {
    const scope = root || document;

    scope.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      // Elementos "texto-puro" (title, option, textarea, select) recebem
      // o texto diretamente; os restantes (spans injetados) também.
      el.textContent = t(key, el.textContent);
    });

    scope.querySelectorAll("[data-i18n-title]").forEach((el) => {
      el.setAttribute("title", t(el.getAttribute("data-i18n-title"), el.getAttribute("title")));
    });

    scope.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder"), el.getAttribute("placeholder")));
    });

    scope.querySelectorAll("[data-i18n-alt]").forEach((el) => {
      el.setAttribute("alt", t(el.getAttribute("data-i18n-alt"), el.getAttribute("alt")));
    });

    document.documentElement.setAttribute("lang", currentLang === "en" ? "en" : "pt-PT");
  }

  /** Muda o idioma ativo, persiste em localStorage, e reaplica as traduções. */
  function setLang(lang) {
    if (!DICTS[lang]) return;
    currentLang = lang;
    localStorage.setItem(STORAGE_KEY, lang);
    applyTranslations();
    document.dispatchEvent(new CustomEvent("i18n:changed", { detail: { lang } }));
  }

  function getLang() {
    return currentLang;
  }

  // Reaplica automaticamente quando novo HTML é injetado dinamicamente
  // (modais, painéis, etc.) desde que chamem window.i18n.apply(container).
  window.i18n = { t, setLang, getLang, apply: applyTranslations };

  /** Liga o botão de alternância de idioma do header, se existir. */
  function wireLangToggle() {
    const btn = document.getElementById("btn-lang-toggle");
    const label = document.getElementById("btn-lang-toggle-label");
    if (!btn) return;

    function refreshLabel() {
      // O botão mostra o idioma para o qual vai mudar (não o atual)
      const target = currentLang === "en" ? "pt" : "en";
      if (label) label.textContent = target.toUpperCase();
      btn.setAttribute("title", currentLang === "en" ? "Português" : "English");
    }

    btn.addEventListener("click", () => {
      setLang(currentLang === "en" ? "pt" : "en");
      refreshLabel();
    });

    document.addEventListener("i18n:changed", refreshLabel);
    refreshLabel();
  }

  document.addEventListener("DOMContentLoaded", () => {
    applyTranslations();
    wireLangToggle();
  });
